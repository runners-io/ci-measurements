#!/usr/bin/env python3
"""Write .github/workflows/G1-timeout-behaviour.yml.

Each job runs a step that never finishes (victim.sh) into `timeout-minutes: 1`, five times, and the steps after it
say which conditions still run. The jobs differ in WHERE the limit is (the job or the step), HOW the victim is
launched (as a child of the step's shell, or with `exec` so it is the step's own process) and whether it handles
SIGINT and SIGTERM (polite) or ignores them (stubborn).
"""
import pathlib

REPS = [1, 2, 3, 4, 5]
HEAD = """name: G1 · what a timeout does

# `timeout-minutes: 1` on a job and on a step, with a step that never finishes, five repetitions of each variant, on
# GitHub-hosted ubuntu-24.04. A public repository, so it costs nothing. Every job is meant to end badly: the question
# is what GitHub does to the process, to the steps after it and to the job's result. GENERATED by
# studies/G1-timeout/scripts/generate.py; studies/G1-timeout/scripts/collect.py reads the answers from the jobs API, the
# job logs and the check-run annotations. Method: studies/G1-timeout/METHOD.md.
on:
  workflow_dispatch:

permissions:
  contents: read

jobs:
"""


def job(name, where, launch, mode, continue_on_error=False):
    job_limit = "    timeout-minutes: 1\n" if where == "job" else "    timeout-minutes: 10\n"
    step_limit = "        timeout-minutes: 1\n" if where == "step" else ""
    coe = "        continue-on-error: true\n" if continue_on_error else ""
    run = f"{'exec ' if launch == 'exec' else ''}studies/G1-timeout/scripts/victim.sh {mode}"
    return f"""  {name}:
    runs-on: ubuntu-24.04
{job_limit}    strategy:
      fail-fast: false
      matrix:
        rep: {REPS}
    name: {name} #${{{{ matrix.rep }}}}
    steps:
      - name: checkout measurements
        uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
      - name: the step that never finishes
        id: victim
{step_limit}{coe}        run: {run}
      - name: next step, no condition
        run: echo "ran -- next step, no condition"
      - name: next step, if success()
        if: success()
        run: echo "ran -- if success()"
      - name: next step, if failure()
        if: failure()
        run: echo "ran -- if failure()"
      - name: next step, if cancelled()
        if: cancelled()
        run: echo "ran -- if cancelled()"
      - name: next step, if always()
        if: always()
        run: echo "ran -- if always()"
"""


jobs = [
    job("job-child-polite", "job", "child", "polite"),
    job("job-child-stubborn", "job", "child", "stubborn"),
    job("job-exec-polite", "job", "exec", "polite"),
    job("job-exec-stubborn", "job", "exec", "stubborn"),
    job("step-child-polite", "step", "child", "polite"),
    job("step-child-stubborn", "step", "child", "stubborn"),
    job("step-exec-polite", "step", "exec", "polite"),
    job("step-exec-stubborn", "step", "exec", "stubborn"),
    job("step-continue-on-error", "step", "exec", "polite", continue_on_error=True),
]
pathlib.Path(".github/workflows/G1-timeout-behaviour.yml").write_text(HEAD + "\n".join(jobs))
