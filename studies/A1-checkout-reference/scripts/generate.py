#!/usr/bin/env python3
"""Write .github/workflows/A1-checkout-inputs.yml: one job per major version of actions/checkout.

`uses:` cannot take an expression, so a matrix cannot choose the version. The workflow is generated from one
template and committed beside this script. The target repository is actions/checkout itself, pinned to the v7.0.1
commit, because it has history, tags and a src/ directory to be sparse about.
"""
import pathlib

VERSIONS = ["v4", "v5", "v6", "v7"]
TARGET = "actions/checkout"
TARGET_SHA = "3d3c42e5aac5ba805825da76410c181273ba90b1"  # v7.0.1

# case name, `with:` inputs
CASES = [
    ("default", {}),
    ("depth0", {"fetch-depth": "0"}),
    ("depth2", {"fetch-depth": "2"}),
    ("depth1-fetch-tags", {"fetch-depth": "1", "fetch-tags": "true"}),
    ("sparse-cone-dir", {"sparse-checkout": "src"}),
    ("sparse-file-non-cone", {"sparse-checkout": "README.md", "sparse-checkout-cone-mode": "false"}),
    ("filter-blobnone", {"filter": "blob:none", "fetch-depth": "0"}),
    ("persist-credentials-false", {"persist-credentials": "false"}),
]

out = ["""name: A1 · actions/checkout, every major version, tested

# Runs the inputs a reference page documents against actions/checkout@v4, @v5, @v6 and @v7 (the floating tags, as a
# workflow that says `@v4` gets them), and records what each leaves in the working copy. GitHub-hosted ubuntu-24.04,
# public repository. GENERATED by studies/A1-checkout-reference/scripts/generate.py: edit that, not this file.
# Method: studies/A1-checkout-reference/METHOD.md.
on:
  workflow_dispatch:

permissions:
  contents: read

jobs:"""]
for v in VERSIONS:
    out.append(f"""  checkout-{v}:
    runs-on: ubuntu-24.04
    timeout-minutes: 15
    name: actions/checkout@{v}
    steps:
      - name: this repository, for the observe script
        uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
        with:
          path: harness
      - name: which commit the floating tag is
        run: |
          echo "version,case,action_runtime,git_version,shallow,commits,tags,files,partial_filter,extraheader_in_git_config,includeif_in_git_config,credential_files_in_runner_temp,output_commit_matches_head,output_ref" > observations.csv
          sha=$(git ls-remote https://github.com/actions/checkout "refs/tags/{v}" "refs/tags/{v}^{{}}" | tail -1 | cut -f1)
          echo "{v},tag-points-at,$sha,,,,,,,,,,," >> observations.csv""")
    for name, inputs in CASES:
        w = "".join(f"          {k}: '{v_}'\n" for k, v_ in inputs.items())
        with_block = f"""        with:
          repository: {TARGET}
          ref: {TARGET_SHA}
          path: t-{name}
{w}""".rstrip("\n") + "\n"
        out.append(f"""      - name: "{name}"
        id: c-{name}
        uses: actions/checkout@{v}
{with_block}      - name: "observe {name}"
        run: harness/studies/A1-checkout-reference/scripts/observe.sh "{v}" "{name}" "t-{name}" "${{{{ steps.c-{name}.outputs.commit }}}}" "${{{{ steps.c-{name}.outputs.ref }}}}" >> observations.csv""")
    out.append(f"""      - name: keep the observations
        uses: actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9 # v7.0.2
        with:
          name: observations-{v}
          path: observations.csv
          retention-days: 14
""")
pathlib.Path(".github/workflows/A1-checkout-inputs.yml").write_text("\n".join(out))
